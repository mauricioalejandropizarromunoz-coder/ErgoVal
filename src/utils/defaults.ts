export function createNewStudyTab(index: number, method: MethodId = MethodId.RULA, customTask?: string): StudyTab {
  const catalog = METHOD_CATALOG.find((m) => m.id === method)!;
  return {
    id: `tab-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    tabLabel: `Estudio ${index}: ${catalog.shortName}`,
    taskEvaluated: customTask || 'Tarea principal del ciclo operativo',
    method,
    payloads: createDefaultPayloads(),
    photos: [],
    instrumentsUsed:
      method === MethodId.FANGER || method === MethodId.WBGT
        ? 'Medidor de estrés térmico de globo y bulbo húmedo, termo-higrómetro y anemómetro calibrado'
        : method === MethodId.ISO_2631 || method === MethodId.ISO_5349
          ? 'Acelerómetro triaxial ponderado en frecuencia conforme a ISO 8041'
          : method === MethodId.NIOSH || method === MethodId.SNOOK || method === MethodId.LMC_295
            ? 'Balanza dinamométrica calibrada, cinta métrica metálica y goniómetro digital'
            : 'Registro fotográfico en verdadera magnitud (plano sagital), goniómetro digital y cronómetro',
    evaluatorObservations: '',
    correctiveMeasures: '',
    responsiblePerson: 'Responsable de Ingeniería / Higiene y Seguridad',
    implementationDeadline: 'Corto plazo',
  };
}
